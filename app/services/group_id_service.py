"""Group ID generation backed by the geo master data.

A Group ID is ``STATE_CODE + CITY_CODE + SEQUENCE`` - ``MP04001`` is the first
group created in Bhopal, Madhya Pradesh; ``MH15002`` is the second in Nashik,
Maharashtra:

* **state code** - the project's two-letter prefix for the State/UT
  (``geo_states.code``, e.g. ``MP``, ``MH``);
* **city code** - the checked-in RTO code for the city (``app.core.rto_codes``;
  Delhi's municipal corporations use the explicit aliases in
  ``app.services.rto_service``) - ``04`` for Bhopal, ``09`` for Indore, ``13``
  for Ujjain, ``15`` for Nashik. This is the same code exposed by ``GET /geo``.
  A city absent from the RTO map falls back to its stored
  ``geo_cities.city_code``; an issued code never changes;
* **sequence** - minimum three digits, zero padded, **per city**, so every
  city counts from ``001`` for itself. Past ``999`` the number simply grows
  (``MP091000``) - it is never truncated, reused or wrapped.

The sequence is a row in ``group_id_counters`` advanced by an atomic
``INSERT ... ON CONFLICT DO UPDATE ... RETURNING``: PostgreSQL serializes
concurrent allocations through the primary key, so two simultaneous creates can
never receive the same number and a restart cannot reset the count. It is never
``COUNT(*) + 1`` and never held in process memory. Before the number is
claimed the counter is raised to the highest sequence the city's rows already
carry, so a counter that lags behind the stored IDs (a restored database, a
corrected city code) can never hand out a number that is already taken.

Only cities present in ``geo_cities`` (seeded by
``scripts/import_geo_data.py`` from LGD data) can be created through
``POST /groups``; anything else is rejected with a 422. Adding a city is a
data change (re-run the import), not a code change.

Group IDs are generated by the backend only. They are never built in the
frontend, never accepted from a client, and never regenerated for a row that
already has one (sheet/directory imports leave ``group_id`` NULL rather than
guessing).

The same service also mints **member IDs** (``members.membership_number``): the
owning group's ID plus a per-group sequence - ``MP09001001`` is the first
member of group ``MP09001``, ``MP09001002`` the second. The counter lives in
``member_id_counters`` with the same atomic upsert, so it works identically
for every state and city. A member ID belongs to one group membership: adding
the same person to another group issues a fresh ID from that group's counter,
and an old number is never reissued.
"""

from __future__ import annotations

from dataclasses import dataclass

from sqlalchemy import Integer, cast, func, select
from sqlalchemy.dialects.postgresql import insert as pg_insert
from sqlalchemy.exc import IntegrityError
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.exceptions import ConflictException, ValidationException
from app.models.geo import GeoCity, GeoState
from app.models.group import GroupIdCounter, MemberIdCounter, SocialGroup
from app.models.member import Member
from app.services.rto_service import rto_code_for_city

#: Sequences are zero padded to at least this many digits.
SEQUENCE_WIDTH = 3


@dataclass(frozen=True)
class CityCode:
    """One configured city: its canonical names and the codes in its Group ID."""

    #: Canonical state name, as it is stored on the group.
    state: str
    #: Two-letter state abbreviation, e.g. ``MP``.
    state_code: str
    #: Canonical city name, as it is stored on the group.
    city: str
    #: Explicit city code, e.g. ``09``.
    city_code: str

    @property
    def prefix(self) -> str:
        """``state_code + city_code``, the scope of this city's sequence."""
        return f"{self.state_code}{self.city_code}"

    @property
    def example(self) -> str:
        return format_group_id(self.prefix, 1)


def _normalize(value: str) -> str:
    """Case-folded, whitespace-collapsed form used for every lookup.

    Deliberately conservative: it never strips digits or punctuation, so
    "Indore 452009" or "Indore - M.P." are *not* silently treated as Indore.
    """
    return " ".join(value.split()).casefold()


async def _find_state(session: AsyncSession, state: str) -> GeoState | None:
    """Find a State/UT by canonical name or two-letter code.

    All 36 rows are loaded and matched in Python against the normalized input
    so "  madhya   pradesh " and "mp" both resolve; the table is tiny and this
    keeps one code path for every spelling rule.
    """
    wanted = _normalize(state)
    if not wanted:
        return None
    result = await session.execute(
        select(GeoState).where(GeoState.is_active.is_(True))
    )
    for candidate in result.scalars().all():
        if _normalize(candidate.name) == wanted or candidate.code.lower() == wanted:
            return candidate
    return None


async def configured_states(session: AsyncSession) -> list[str]:
    result = await session.execute(
        select(GeoState.name)
        .where(GeoState.is_active.is_(True))
        .order_by(GeoState.name)
    )
    return list(result.scalars().all())


async def cities_for_state(session: AsyncSession, state: str) -> list[CityCode]:
    state_row = await _find_state(session, state)
    if state_row is None:
        return []
    result = await session.execute(
        select(GeoCity)
        .where(GeoCity.state_id == state_row.id, GeoCity.is_active.is_(True))
        .order_by(GeoCity.name)
    )
    return [
        CityCode(
            state=state_row.name,
            state_code=state_row.code,
            city=city.name,
            city_code=(
                rto_code_for_city(state_row.code, city.name, city.lgd_code)
                or city.city_code
            ),
        )
        for city in result.scalars().all()
    ]


async def resolve_city(
    session: AsyncSession, state: str, city: str
) -> CityCode:
    """Validate a client-supplied state/city pair against the geo master data.

    Returns the canonical :class:`CityCode` to store and to build the Group ID
    from. Raises a 422 :class:`ValidationException` for an unknown state, a
    city that does not exist in that state, an ambiguous city name, or a city
    that belongs to a different state - so a typo or a mismatched pair can
    never mint an ID for the wrong place.
    """
    state_row = await _find_state(session, state)
    if state_row is None:
        raise ValidationException(
            f"Unknown state or union territory '{state.strip()}'. "
            "Use GET /api/v1/geo/states for the list of configured states."
        )

    wanted = _normalize(city)
    result = await session.execute(
        select(GeoCity).where(
            GeoCity.state_id == state_row.id,
            GeoCity.name_norm == wanted,
            GeoCity.is_active.is_(True),
        )
    )
    matches = list(result.scalars().all())

    if len(matches) == 1:
        only = matches[0]
        # Prefer RTO code mapping: STATE + RTO_CODE(2 digits) + SEQ(3 digits)
        rto_code = rto_code_for_city(
            state_row.code, only.name, only.lgd_code
        ) or rto_code_for_city(state_row.code, city)
        if rto_code:
            return CityCode(
                state=state_row.name,
                state_code=state_row.code,
                city=only.name,
                city_code=rto_code,
            )
        return CityCode(
            state=state_row.name,
            state_code=state_row.code,
            city=only.name,
            city_code=only.city_code,
        )

    if len(matches) > 1:
        raise ValidationException(
            f"City name '{city.strip()}' is ambiguous in {state_row.name} "
            f"(multiple LGD entries: "
            f"{', '.join(str(m.lgd_code) for m in matches)}). "
            "Contact an administrator to disambiguate this city."
        )

    # City unknown in this state: explain whether it exists elsewhere.
    elsewhere = await session.execute(
        select(GeoCity.name, GeoState.name)
        .join(GeoState, GeoCity.state_id == GeoState.id)
        .where(GeoCity.name_norm == wanted, GeoCity.is_active.is_(True))
        .limit(5)
    )
    rows = elsewhere.all()
    if rows:
        places = ", ".join(f"{name} ({st})" for name, st in rows)
        raise ValidationException(
            f"City '{city.strip()}' does not belong to {state_row.name}. "
            f"It is configured under: {places}."
        )

    raise ValidationException(
        f"City '{city.strip()}' is not configured in {state_row.name}. "
        "Use GET /api/v1/geo/states/"
        f"{state_row.name}/cities for the list of cities."
    )


async def _highest_stored_sequence(session: AsyncSession, city: CityCode) -> int:
    """The highest sequence already stored for a city, ``0`` when it has none.

    Only the rows of *this* city count: the ID's prefix is matched and the
    canonical state/city names have to agree, so a longer prefix of another
    city (``MP247`` against ``MP24``) can never be mistaken for this one's
    sequence.
    """
    remainder = func.substring(SocialGroup.group_id, len(city.prefix) + 1)
    result = await session.execute(
        select(func.max(cast(remainder, Integer))).where(
            SocialGroup.group_id.like(f"{city.prefix}%"),
            SocialGroup.state == city.state,
            SocialGroup.city == city.city,
            remainder.op("~")("^[0-9]+$"),
        )
    )
    return int(result.scalar() or 0)


async def _raise_counter_to_stored_highest(
    session: AsyncSession, city: CityCode
) -> None:
    """Never let the counter fall behind the IDs the city already carries.

    The counter is the primary source of truth, but it can lag behind the
    stored rows - a database restored from a backup, a city whose code was
    corrected, an ID written by hand. Raising the counter to the highest
    sequence already stored keeps the next allocation unique without ever
    lowering a counter (the number of a deleted group is never reissued).
    """
    highest = await _highest_stored_sequence(session, city)
    if not highest:
        return
    await session.execute(
        pg_insert(GroupIdCounter)
        .values(city_key=city.prefix, last_value=highest)
        .on_conflict_do_update(
            index_elements=[GroupIdCounter.city_key],
            set_={
                "last_value": func.greatest(
                    GroupIdCounter.last_value, highest
                )
            },
        )
    )


async def next_sequence(session: AsyncSession, city: CityCode) -> int:
    """Atomically claim the next sequence number for a city.

    ``ON CONFLICT ... DO UPDATE`` takes a row lock on the counter for the rest
    of the transaction, so concurrent creators in the same city line up instead
    of racing; a rolled-back request returns its number to the pool because the
    increment rolls back with it. The counter is first raised to the highest
    sequence the city already uses, so a number that is stored is never handed
    out twice.
    """
    await _raise_counter_to_stored_highest(session, city)
    statement = (
        pg_insert(GroupIdCounter)
        .values(city_key=city.prefix, last_value=1)
        .on_conflict_do_update(
            index_elements=[GroupIdCounter.city_key],
            set_={"last_value": GroupIdCounter.last_value + 1},
        )
        .returning(GroupIdCounter.last_value)
    )
    return int((await session.execute(statement)).scalar_one())


async def next_group_id(session: AsyncSession, city: CityCode) -> str:
    """The next Group ID for a city, e.g. ``MP04001`` then ``MP04002``."""
    return format_group_id(city.prefix, await next_sequence(session, city))


def format_group_id(prefix: str, sequence: int) -> str:
    """``MP09`` + ``1`` -> ``MP09001``. Grows past three digits, never truncates."""
    return f"{prefix}{sequence:0{SEQUENCE_WIDTH}d}"


# --- member IDs (members.membership_number) ---------------------------------


async def _highest_stored_member_sequence(
    session: AsyncSession, group_id: str
) -> int:
    """Find the highest integer sequence this group's members already carry."""
    remainder = func.substr(Member.membership_number, len(group_id) + 1)
    result = await session.execute(
        select(func.max(cast(remainder, Integer))).where(
            Member.membership_number.like(f"{group_id}%"),
            remainder.op("~")("^[0-9]+$"),
        )
    )
    return int(result.scalar() or 0)


async def _raise_member_counter_to_stored_highest(
    session: AsyncSession, group_id: str
) -> None:
    """Never let the member counter fall behind the IDs the group already carries."""
    highest = await _highest_stored_member_sequence(session, group_id)
    if not highest:
        return
    await session.execute(
        pg_insert(MemberIdCounter)
        .values(group_id=group_id, last_value=highest)
        .on_conflict_do_update(
            index_elements=[MemberIdCounter.group_id],
            set_={
                "last_value": func.greatest(
                    MemberIdCounter.last_value, highest
                )
            },
        )
    )


async def next_member_sequence(session: AsyncSession, group_id: str) -> int:
    """Atomically claim the next member sequence inside one group.

    Same mechanism as :func:`next_sequence`, keyed by the Group ID instead of
    the city prefix: concurrent ``POST /groups/{id}/members`` calls serialize on
    the ``member_id_counters`` primary key, and a rolled-back request returns
    its number because the increment rolls back with the transaction.
    """
    await _raise_member_counter_to_stored_highest(session, group_id)
    statement = (
        pg_insert(MemberIdCounter)
        .values(group_id=group_id, last_value=1)
        .on_conflict_do_update(
            index_elements=[MemberIdCounter.group_id],
            set_={"last_value": MemberIdCounter.last_value + 1},
        )
        .returning(MemberIdCounter.last_value)
    )
    return int((await session.execute(statement)).scalar_one())


def format_member_id(group_id: str, sequence: int) -> str:
    """``MP09001`` + ``1`` -> ``MP09001001``.

    The member ID is always the owning group's ID followed by the per-group
    sequence, so any member ID can be attributed to its group by the prefix.
    Grows past three digits, never truncates or wraps.
    """
    return f"{group_id}{sequence:0{SEQUENCE_WIDTH}d}"


async def next_member_id(session: AsyncSession, group_id: str) -> str:
    """The next member ID for a group, e.g. ``MP09001001`` then ``MP09001002``."""
    return format_member_id(
        group_id, await next_member_sequence(session, group_id)
    )


def membership_number_matches(
    membership_number: str | None, group_id: str
) -> bool:
    """Whether a stored member ID was issued by this group.

    ``True`` only when the number is this Group ID followed by a digit-only
    sequence (``MP09001001`` for ``MP09001``); ``False`` for ``None``, for a
    number from a different group (the member is moving between groups), or
    for a client-supplied value that never came from a counter. The check is
    prefix-based by construction: member IDs are *built* as
    ``group_id + sequence``, so this never has to parse or guess.
    """
    if not membership_number or not membership_number.startswith(group_id):
        return False
    remainder = membership_number[len(group_id):]
    return len(remainder) >= SEQUENCE_WIDTH and remainder.isdigit()


def _is_membership_number_violation(exc: IntegrityError) -> bool:
    """True when the unique constraint on ``members.membership_number`` fired.

    Same shape as ``_is_group_id_violation`` in the groups API: match the
    constraint name when the driver exposes it, otherwise the message, so a
    violation of some other constraint keeps its usual path.
    """
    constraint = getattr(getattr(exc, "orig", None), "constraint_name", None)
    return "membership_number" in (constraint or "") or "membership_number" in str(
        exc
    )


async def assign_member_id(
    session: AsyncSession, member: Member, group: SocialGroup
) -> bool:
    """Give a member their ID for the group they are in, then persist it.

    Called on every path that puts a member into a group (creation with a
    group, adding/moving via ``POST /groups/{id}/members``). Idempotent: a
    member who already carries an ID issued by this group keeps it, a member
    entering a different group gets a fresh ID from the new group's counter
    (the old number is never returned to the pool), and a member with no ID
    yet (created before member IDs existed) is backfilled on first touch.

    The flush runs here so the counter claim, the number and any pending group
    change commit or roll back as one unit; the unique backstop on
    ``membership_number`` turns the (theoretical) hand-inserted collision into
    a 409 instead of a duplicate ID.
    """
    if not group.group_id or membership_number_matches(
        member.membership_number, group.group_id
    ):
        return False
    member.membership_number = await next_member_id(session, group.group_id)
    try:
        await session.flush()
    except IntegrityError as exc:
        await session.rollback()
        if _is_membership_number_violation(exc):
            raise ConflictException(
                "Could not allocate a unique member ID for this group; "
                "retry the request."
            ) from exc
        raise
    return True
