@dataclass(frozen=True)
class RtoEntry:
    state_code: str
    rto_code: str
    names: tuple[str, ...]


def parse_rto_rows(rows: list[str] | tuple[str, ...]) -> list[RtoEntry]:
    entries: list[RtoEntry] = []
    for row in rows:
        parts = row.split("|")
        if len(parts) < 3:
            continue
        state_code = parts[0].strip().upper()
        rto_code = parts[1].strip()
        names = tuple(name.strip().lower() for name in parts[2:] if name.strip())
        entries.append(RtoEntry(state_code=state_code, rto_code=rto_code, names=names))
    return entries


RTO_ENTRIES = parse_rto_rows(INDIA_RTO_ROWS)
RTO_BY_STATE: dict[str, list[RtoEntry]] = {}
for entry in RTO_ENTRIES:
    RTO_BY_STATE.setdefault(entry.state_code, []).append(entry)


def get_rto_code(state_code: str, city_name: str) -> str | None:
    """Find RTO code for a city/name. Returns 2-digit code or None."""
    state_code = state_code.strip().upper()
    needle = " ".join(city_name.lower().strip().split())
    for entry in RTO_BY_STATE.get(state_code, []):
        for name in entry.names:
            n = " ".join(name.split())
            if n == needle or needle in n or n in needle:
                # Return zero-padded to 2 digits
                try:
                    return f"{int(entry.rto_code):02d}"
                except ValueError:
                    return entry.rto_code.zfill(2)
    return None


def normalize_rto_code(code: str) -> str:
    """Normalize to 2 digits."""
    try:
        return f"{int(code):02d}"
    except ValueError:
        return code.strip().zfill(2)


def build_group_id(state_code: str, rto_code: str, sequence: int) -> str:
    """Build group ID in format: STATE_CODE + RTO_CODE(2) + SEQ(3+)"""
    state_code = state_code.strip().upper()
    rto_code = normalize_rto_code(rto_code)
    seq = str(sequence)
    if len(seq) < 3:
        seq = seq.zfill(3)
    return f"{state_code}{rto_code}{seq}"


def build_member_id(group_id: str, member_sequence: int) -> str:
    """Build member ID in format: GROUP_ID + MEMBER_SEQ(3+)"""
    seq = str(member_sequence)
    if len(seq) < 3:
        seq = seq.zfill(3)
    return f"{group_id}{seq}"
